#!/bin/sh
# Find OpenSSL (1.1.1 or later) for TLS, at build time.
#   sh openssl_config.sh CFLAGS_SEXP LIBS_SEXP CONFIG_ML
# Tries, in order: $VELA_OPENSSL (an install prefix), pkg-config (with the
# usual Homebrew prefixes added to its search path), then the system
# headers (Linux: the libssl-dev / openssl-devel package). The flags found
# are checked by compiling and linking a small program. If nothing works,
# vela is built without TLS: https and the *_tls methods then fail with an
# error saying so, and everything else is unaffected.
cflags_out=$1 libs_out=$2 ml_out=$3
cc=${CC:-cc}
tmp=$(mktemp -d 2>/dev/null || mktemp -d -t vela-ossl)
trap 'rm -rf "$tmp"' EXIT
cat >"$tmp/t.c" <<'EOF'
#include <openssl/ssl.h>
#include <openssl/x509v3.h>
#if OPENSSL_VERSION_NUMBER < 0x10101000L
#error "OpenSSL 1.1.1 or later is needed"
#endif
int main(void) { SSL_CTX *c = SSL_CTX_new(TLS_client_method()); SSL_CTX_free(c); return 0; }
EOF

works() { # $1 = cflags, $2 = libs
  $cc $1 "$tmp/t.c" -o "$tmp/t" $2 >/dev/null 2>&1
}

cflags= libs= found=
try() {
  if [ -z "$found" ] && works "$1" "$2"; then cflags=$1 libs=$2 found=1; fi
}

if [ -n "$VELA_OPENSSL" ]; then
  try "-I$VELA_OPENSSL/include" "-L$VELA_OPENSSL/lib -lssl -lcrypto"
fi
if command -v pkg-config >/dev/null 2>&1; then
  pcp=
  for p in /opt/homebrew/opt/openssl@3 /usr/local/opt/openssl@3 /opt/homebrew/opt/openssl /usr/local/opt/openssl; do
    [ -d "$p/lib/pkgconfig" ] && pcp="$pcp${pcp:+:}$p/lib/pkgconfig"
  done
  pc=$(PKG_CONFIG_PATH="$pcp${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}" pkg-config --cflags --libs openssl 2>/dev/null) && {
    pcc=$(PKG_CONFIG_PATH="$pcp${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}" pkg-config --cflags openssl)
    pcl=$(PKG_CONFIG_PATH="$pcp${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}" pkg-config --libs openssl)
    try "$pcc" "$pcl"
  }
fi
try "" "-lssl -lcrypto"

sexp() { # words -> ("w1" "w2" ...)
  printf '('
  for w in $1; do printf ' "%s"' "$w"; done
  printf ' )\n'
}
mllist() {
  printf '['
  sep=
  for w in $1; do printf '%s "%s"' "$sep" "$w"; sep=';'; done
  printf ' ]'
}

if [ -n "$found" ]; then
  sexp "-DVELA_TLS $cflags" >"$cflags_out"
  sexp "$libs" >"$libs_out"
  {
    echo "(* Generated by openssl_config.sh: how to compile and link against OpenSSL. *)"
    echo "let found = true"
    echo "let cflags = $(mllist "$cflags")"
    echo "let libs = $(mllist "$libs")"
  } >"$ml_out"
else
  echo "()" >"$cflags_out"
  echo "()" >"$libs_out"
  {
    echo "(* Generated by openssl_config.sh: OpenSSL was not found, so no TLS. *)"
    echo "let found = false"
    echo "let cflags : string list = []"
    echo "let libs : string list = []"
  } >"$ml_out"
fi
